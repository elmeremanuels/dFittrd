import { BASE_SHAPE_ID, bodyShape, buildMannequin, buildMannequinMesh } from '@curtain/mannequin';
import { buildBundle } from '../../src/bundle';
import { bodyField, buildAvatar, mannequinMeasurements } from './body';
import { meshFromGlb, type SpikeBundle } from './bundle';
import { openSession, prepareFit, relax, viewerMaterial } from './engine';
import { fitForBody } from './fitting';
const m = buildMannequin(bodyShape(BASE_SHAPE_ID));
const canonical = buildMannequinMesh(m);
const id = (process.env.ID ?? 'monochrome-03') as 'monochrome-03';
const b = buildBundle(id, { skipSeparation: true });
const bundle: SpikeBundle = { productId: id, anchors: JSON.parse(b.files['anchors.json']), grading: JSON.parse(b.files['grading.json']), material: JSON.parse(b.files['material.json']), qa: JSON.parse(b.files['qa.json']), baseMesh: meshFromGlb(b.files['base.glb']) };
const s = openSession(m, bundle);
const meas = mannequinMeasurements(m);
const av = buildAvatar(m, canonical, meas);
const f = prepareFit(s, av, bodyField(m, av), fitForBody(s.payload, meas), process.env.SIZE ?? 'M', viewerMaterial('product', bundle.material));
const c = f.cloth;
const st = () => { const out: [number, string][] = []; for (let e = 0; e < c.edgeRest.length; e++) { const a = c.edges[2*e]!, bb = c.edges[2*e+1]!; const d = Math.hypot(c.pos[3*a]!-c.pos[3*bb]!, c.pos[3*a+1]!-c.pos[3*bb+1]!, c.pos[3*a+2]!-c.pos[3*bb+2]!); const v = d / c.edgeRest[e]! - 1; if (v > 0.15) out.push([v, `${(v*100).toFixed(0)}% rest=${c.edgeRest[e]!.toFixed(2)} pin=${f.pinned[a]}${f.pinned[bb]} ch=${s.chains[a]}${s.chains[bb]} nc=${f.noCollide[a]}${f.noCollide[bb]} a=(${c.pos[3*a]!.toFixed(1)},${c.pos[3*a+1]!.toFixed(1)},${c.pos[3*a+2]!.toFixed(1)}) b=(${c.pos[3*bb]!.toFixed(1)},${c.pos[3*bb+1]!.toFixed(1)},${c.pos[3*bb+2]!.toFixed(1)})`]); } return out.sort((p,q)=>q[0]-p[0]).map(x=>x[1]); };
console.log('start', st().slice(0,6));
relax(f);
const after = st(); console.log('after', after.length, after.slice(0, 10));
